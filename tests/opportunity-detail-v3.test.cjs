const test = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { join } = require('node:path')

const read = path => readFileSync(join(__dirname, '..', path), 'utf8')

test('detail V3 is an evidence-first two-column overview with unknown safety states', () => {
  const app = read('src/App.jsx')
  const sidebar = read('src/components/OpportunityDecisionSidebar.jsx')
  const css = read('src/components/OpportunityDecisionSidebar.css')
  assert(app.includes('<OpportunityDecisionSidebar opportunity={opportunity}'))
  assert(app.includes('className="opp-v3-hero"'))
  assert(app.includes('className="opp-v3-drawer absolute'))
  assert(sidebar.includes('Not independently verified'))
  assert(sidebar.includes('No trusted payment verification result is stored'))
  assert(sidebar.includes('Off-platform payment/request'))
  assert(sidebar.includes('Not assessed'))
  assert(sidebar.includes("view.budget.kind === 'listed'"))
  assert(sidebar.includes("getResearchStatusDetails(opportunity)"))
  assert(sidebar.includes('getOpportunityPresentation(opportunity)'))
  assert(css.includes('@media(max-width:820px)'))
  assert(css.includes('@media(max-width:600px)'))
})

test('detail V3 retains existing guarded pitch and sales actions', () => {
  const app = read('src/App.jsx')
  const sidebar = read('src/components/OpportunityDecisionSidebar.jsx')
  assert(app.includes("onGeneratePitch={() => void handleGenerateManualPitch(selectedOpportunity)}"))
  assert(app.includes('pitchGenerating={manualPitchId === selectedOpportunity?.id}'))
  assert(app.includes('onGeneratePitch={onGeneratePitch}'))
  assert(sidebar.includes('onClick={onGeneratePitch}'))
  assert(sidebar.includes("outreach_status === 'not_generated'"))
  assert(sidebar.includes('Nothing is sent automatically'))
  assert(app.includes('id="opp-v3-outreach-draft"'))
  assert(app.includes('<DrawerSection title="Opportunity Status">'))
  assert(app.includes('onScheduleFollowUp={scheduleOpportunityFollowUp}'))
  assert(app.includes('onAddNote={addOpportunityNote}'))
  assert(app.includes("refreshedOpportunities || []"))
})
