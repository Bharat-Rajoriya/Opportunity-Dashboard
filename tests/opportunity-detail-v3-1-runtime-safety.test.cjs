const test = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { join } = require('node:path')
const { pathToFileURL } = require('node:url')
const read = p => readFileSync(join(__dirname,'..',p),'utf8')

test('regression: no pitch error never reads null.message when selected id is undefined', async () => {
  const { getOpportunityPitchError, getOpportunityPitchState } = await import(pathToFileURL(join(__dirname,'../src/lib/opportunityDetailSafety.js')).href)
  assert.equal(getOpportunityPitchError(null, undefined), '')
  assert.equal(getOpportunityPitchError(null, 'abc'), '')
  assert.equal(getOpportunityPitchError(undefined, undefined), '')
  assert.equal(getOpportunityPitchError({ id:'abc', message:'Some error' },'def'), '')
  assert.equal(getOpportunityPitchError({ id:'abc', message:'Some error' },'abc'), 'Some error')
  assert.equal(getOpportunityPitchError({ id:'abc', message:null },'abc'), '')
  assert.deepEqual(getOpportunityPitchState(null), { hasDraft:false, canGenerate:true })
  assert.deepEqual(getOpportunityPitchState({ outreach_message:'Draft', outreach_status:'drafted' }), { hasDraft:true, canGenerate:false })
})

test('drawer isolates failure, keeps original controls, and never invents identity or payment facts', () => {
  const app=read('src/App.jsx')
  const sidebar=read('src/components/OpportunityDecisionSidebar.jsx')
  const boundary=read('src/components/OpportunityDrawerErrorBoundary.jsx')
  assert(app.includes('getOpportunityPitchError(manualPitchError, selectedOpportunity?.id)'))
  assert(!app.includes('manualPitchError?.id === selectedOpportunity?.id'))
  assert(app.includes('<OpportunityDrawerErrorBoundary opportunityId={selectedOpportunity?.id}'))
  assert(app.includes('opp-v31-overview'))
  assert(app.includes('<OpportunityDecisionSidebar opportunity={opportunity}'))
  assert(app.includes('<DrawerSection title="Research status">'))
  assert(app.includes('<DrawerSection title="AI Outreach Draft">'))
  assert(app.includes('<DrawerSection title="Opportunity Status">'))
  assert(app.includes('onScheduleFollowUp={scheduleOpportunityFollowUp}'))
  assert(app.includes('onAddNote={addOpportunityNote}'))
  assert(sidebar.includes('Payment verification'))
  assert(sidebar.includes('Unknown'))
  assert(sidebar.includes('Unverified'))
  assert(sidebar.includes('Not assessed'))
  assert(sidebar.includes('No message is sent automatically'))
  assert(boundary.includes('getDerivedStateFromError'))
  assert(boundary.includes('Opportunity details unavailable'))
})

