const test = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { join } = require('node:path')
const read = path => readFileSync(join(__dirname, '..', path), 'utf8')

test('handoff is a deliberate, guarded action and is never an automatic AI score', () => {
  const panel = read('src/components/QuickCapturePanel.jsx')
  const service = read('src/services/manualCaptures.js')
  assert(panel.includes('window.confirm('))
  assert(panel.includes('Submit for qualification'))
  assert(panel.includes('submitManualCaptureForQualification(workspaceId, record.id)'))
  assert(panel.includes('Saved to the qualification queue. Select Run AI qualification'))
  assert(!panel.includes('Automated qualification is not yet connected'))
  assert(panel.includes("record.status === 'pending_qualification'"))
  assert(panel.includes("record.status === 'needs_review'"))
  assert(service.includes(".rpc('submit_manual_capture_for_qualification'"))
  assert(!service.includes('.from(\'opportunities\').insert('))
  assert(!panel.includes('triggerOpportunityEngine'))
  assert(!panel.includes('supabase.functions.invoke'))
})

test('database transition verifies owner, serializes and blocks duplicate qualified URLs', () => {
  const sql = read('supabase/migrations/20261108101701_manual_capture_qualification_handoff_v1.sql')
  assert(sql.includes('language plpgsql security invoker'))
  assert(sql.includes('auth.uid() is null'))
  assert(sql.includes('owner_user_id = auth.uid()'))
  assert(sql.includes('for update'))
  assert(sql.includes("capture.status <> 'needs_review'"))
  assert(sql.includes('from public.opportunities o'))
  assert(sql.includes('o.workspace_id = p_workspace_id'))
  assert(sql.includes("raise exception 'already_captured_opportunity'"))
  assert(sql.includes("set status = 'pending_qualification'"))
  assert(sql.includes('submitted_for_qualification_at = now()'))
  assert(sql.includes('grant execute on function public.submit_manual_capture_for_qualification'))
  assert(sql.includes('to authenticated'))
})

test('status cannot be treated as scored or active processing', () => {
  const notes = read('docs/manual-capture-qualification-handoff.md')
  const panel = read('src/components/QuickCapturePanel.jsx')
  assert(notes.includes('qualification worker has not been wired'))
  assert(notes.includes('not presently processing'))
  assert(panel.includes('Run AI qualification'))
  assert(panel.includes('Accepted — manual review needed'))
  assert(panel.includes('No opportunity was created.'))
})
