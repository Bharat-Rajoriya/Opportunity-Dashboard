const test = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { join } = require('node:path')
const read = p => readFileSync(join(__dirname, '..', p), 'utf8')

test('owner may delete only unprocessed review captures', () => {
  const sql = read('supabase/migrations/20261109101000_manual_capture_stale_recovery_guard_v1.sql')
  assert.match(sql, /drop policy if exists "Owner delete manual captures"/)
  assert.match(sql, /status in \('needs_review','dismissed'\)/)
  assert.match(sql, /w.owner_user_id=\(select auth.uid\(\)\)/)
})

test('recovery is service-role-only, strictly stale and never requeues work', () => {
  const sql = read('supabase/migrations/20261109101000_manual_capture_stale_recovery_guard_v1.sql')
  assert.match(sql, /current_user <> 'service_role'/)
  assert.match(sql, /w.owner_user_id=p_user_id and w.active=true/)
  assert.match(sql, /for update/)
  assert.match(sql, /c.status <> 'qualifying'/)
  assert.match(sql, /qualification_started_at > now\(\) - interval '180 seconds'/)
  assert.match(sql, /set status='failed'/)
  assert.match(sql, /qualification_lease=null/)
  assert.match(sql, /retry_scheduled',false/)
  assert.match(sql, /to service_role/)
  assert.doesNotMatch(sql, /set status='pending_qualification'/)
  assert.doesNotMatch(sql, /qualification_attempts\s*=\s*0/)
})

test('recovery endpoint requires user JWT and ownership, never sends to n8n', () => {
  const edge = read('supabase/functions/recover-stalled-manual-capture/index.ts')
  assert.match(edge, /withSupabase\(\{ auth: 'user' \}/)
  assert.match(edge, /ctx.jwtClaims\?\.sub/)
  assert.match(edge, /ctx.supabase\s*\.from\('workspaces'\)/)
  assert.match(edge, /ctx.supabase\s*\.from\('manual_capture_reviews'\)/)
  assert.match(edge, /ctx.supabaseAdmin.rpc\(/)
  assert.match(edge, /'expire_stalled_manual_capture_qualification'/)
  assert.doesNotMatch(edge, /N8N_WEBHOOK_SECRET/)
  assert.doesNotMatch(edge, /fetch\(/)
  assert.doesNotMatch(edge, /'finish_manual_capture_qualification'/)
})

test('recovery UI requires explicit confirmation and expired worker start', () => {
  const ui = read('src/components/QuickCapturePanel.jsx')
  const svc = read('src/services/manualCaptures.js')
  assert.match(ui, /Resolve stalled run/)
  assert.match(ui, /Date.now\(\) - new Date\(record.qualification_started_at\).getTime\(\) > 180000/)
  assert.match(ui, /window.confirm\('Mark this expired AI qualification as failed/)
  assert.match(svc, /supabase.functions.invoke\('recover-stalled-manual-capture'/)
  assert.match(svc, /data.retry_scheduled !== false/)
})
