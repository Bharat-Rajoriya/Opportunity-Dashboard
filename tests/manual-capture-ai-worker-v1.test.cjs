test('n8n workflow is classification only, configured with protected webhook and model', () => {
  const workflow = JSON.parse(read('automation/manual-capture-ai-qualification-workflow.json'))
  const types = workflow.nodes.map(n => n.type)
  const auth = workflow.nodes.find(n => n.type === 'n8n-nodes-base.webhook')
  assert.equal(auth.parameters.authentication, 'headerAuth')
  assert(types.includes('@n8n/n8n-nodes-langchain.informationExtractor'))
  assert(types.includes('@n8n/n8n-nodes-langchain.lmChatOpenAi'))
  assert(types.includes('n8n-nodes-base.respondToWebhook'))
  assert(!types.includes('n8n-nodes-base.supabase'))
  assert(!types.includes('n8n-nodes-base.emailSend'))
  assert(!types.includes('n8n-nodes-base.httpRequest'))
})

