test('manual capture worker uses authenticated user context and private server credentials', () => {
  const edge = read('supabase/functions/qualify-manual-capture/index.ts')
  assert(edge.includes("withSupabase({ auth: 'user' }"))
  assert(edge.includes("ctx.supabase.from('manual_capture_reviews')"))
  assert(edge.includes(".from('workspaces')"))
  assert(edge.includes(".from('services')"))
  assert(edge.includes('ctx.supabaseAdmin.rpc('))
  assert(edge.includes("'claim_manual_capture_qualification'"))
  assert(edge.includes("'finish_manual_capture_qualification'"))
  assert(edge.includes("'fail_manual_capture_qualification'"))
  assert(edge.includes("Deno.env.get('N8N_WEBHOOK_SECRET')"))
  assert(edge.includes("x-opportunity-engine-key"))
  assert(!edge.includes('VITE_N8N'))
  assert(!edge.includes('OPENAI_API_KEY'))
  assert(edge.includes('classification.source_verified !== false'))
  assert(edge.includes('controller.abort()'))
})

