const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.join(__dirname, '../n8n/research-recovery-v1')
const graph = JSON.parse(fs.readFileSync(path.join(root, 'activation-manifest.json'), 'utf8'))
const byName = Object.fromEntries(graph.nodes.map(node => [node.name, node]))
const code = name => fs.readFileSync(path.join(root, name + '.n8n.txt'), 'utf8')
const branch = (from, index, to) => assert.ok(byName[from].connections[index]?.includes(to), from + ' missing path to ' + to)

test('shared SerpApi recovery claims a service-role lease before search', () => {
  assert.equal(graph.shared_provider, 'serpapi')
  branch('Can Research Company?', 0, 'Research Recovery Required?')
  branch('Research Recovery Required?', 0, 'Claim Research Recovery Lease')
  branch('Claim Research Recovery Lease', 0, 'Authorize Research Recovery Probe')
  branch('Research Probe Authorized?', 0, 'Research Prospect')
  branch('Research Probe Authorized?', 1, 'Partial Research')
  assert.match(byName['Can Research Company?'].gate, /Recover Research Context/)
  assert.match(byName['Can Research Company?'].gate, /Claim Research Recovery Lease/)
  assert.match(byName['Claim Research Recovery Lease'].http_url, /claim_provider_recovery_probe$/)
  assert.deepEqual(byName['Claim Research Recovery Lease'].credential_types, ['supabaseApi'])
  assert.match(code('authorize-research-recovery-probe'), /grant\.granted === true/)
  assert.match(code('authorize-research-recovery-probe'), /opportunity\.workspace_id/)
})

test('success requires token-checked completion before full company research', () => {
  branch('Research Prospect', 0, 'Validate Research Provider Response')
  branch('Research Response Valid?', 0, 'Research Success Was Probe?')
  branch('Research Success Was Probe?', 0, 'Complete Research Recovery Success')
  branch('Complete Research Recovery Success', 0, 'Restore Completed Research Response')
  branch('Research Completion Confirmed?', 0, 'Build Research Packet')
  branch('Research Completion Confirmed?', 1, 'Partial Research')
  assert.match(byName['Complete Research Recovery Success'].request_body, /p_lease_token/)
  assert.match(code('validate-research-provider-response'), /search_metadata/)
  assert.match(code('restore-completed-research-response'), /confirmed/)
})

test('failure recovery uses lease or guarded service RPC, never direct circuit write', () => {
  branch('Research Prospect', 1, 'Recover Research Context')
  branch('Research Response Valid?', 1, 'Recover Research Context')
  branch('Recover Research Context', 0, 'Research Failure Was Probe?')
  branch('Research Failure Was Probe?', 0, 'Complete Research Recovery Failure')
  branch('Research Failure Was Probe?', 1, 'Record Normal Research Failure Safely')
  branch('Complete Research Recovery Failure', 0, 'Restore Partial Context After Provider Error')
  branch('Record Normal Research Failure Safely', 0, 'Restore Partial Context After Provider Error')
  assert.match(byName['Complete Research Recovery Failure'].http_url, /complete_provider_recovery_probe$/)
  assert.match(byName['Record Normal Research Failure Safely'].http_url, /record_provider_failure_if_unleased$/)
  assert.ok(!byName['Record SerpApi Cooldown (Research)'])
  for(const key of ['Research Prospect','Claim Research Recovery Lease','Complete Research Recovery Success','Complete Research Recovery Failure','Record Normal Research Failure Safely']) {
    assert.equal(byName[key].retryOnFail, false)
  }
  assert.match(code('recover-research-context'), /_research_recovery_token/)
})

test('no paid provider calls were made in staged success, 429 and denial tests', () => {
  assert.equal(graph.test_executions.recovery_success, '2648')
  assert.equal(graph.test_executions.recovery_429, '2649')
  assert.equal(graph.test_executions.lease_denied, '2650')
  assert.equal(graph.production_enabled, false)
})
