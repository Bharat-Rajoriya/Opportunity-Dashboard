const test = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { join } = require('node:path')
const read = p => readFileSync(join(__dirname, '..', p), 'utf8')

test('Freelancer verifier never fetches arbitrary user URLs or accepts client-provided IDs', () => {
  const edge = read('supabase/functions/verify-manual-freelancer-source/index.ts')
  assert(edge.includes("withSupabase({ auth: 'user' }"))
  assert(edge.includes("['www.freelancer.com','freelancer.com'].includes"))
  assert(edge.includes("u.protocol !== 'https:'"))
  assert(edge.includes("u.pathname.startsWith('/projects/')"))
  assert(edge.includes("freelancerProjectId(capture.source_url)"))
  assert(!edge.includes('body?.source_url'))
  assert(!edge.includes('body?.project_id'))
  assert(edge.includes("Deno.env.get('N8N_WEBHOOK_SECRET')"))
  assert(edge.includes("x-opportunity-engine-key"))
  assert(edge.includes('buyer_identity_verified !== false'))
  assert(edge.includes('payment_verified !== false'))
})
test('provider evidence is recorded by service role, no score upgrades or outreach', () => {
  const sql = read('supabase/migrations/20261108232000_manual_freelancer_provider_check_v1.sql')
  assert(sql.includes("current_user <> 'service_role'"))
  assert(sql.includes("c.status <> 'qualified'"))
  assert(sql.includes("c.source_platform <> 'freelancer'"))
  assert(sql.includes('o.workspace_id=p_workspace_id'))
  assert(sql.includes("o.source_item_id=c.id::text"))
  assert(sql.includes('security invoker'))
  assert(sql.includes('to service_role'))
  assert(!sql.includes("source_verified',true"))
  assert(!sql.includes("total_score="))
  assert(!sql.includes("outreach_status="))
})
test('UI calls explicit on-demand verification and uses scoped evidence label', () => {
  const ui = read('src/components/QuickCapturePanel.jsx')
  const service = read('src/services/manualCaptures.js')
  assert(ui.includes('Check via Freelancer API'))
  assert(ui.includes('verifyManualFreelancerSource(workspaceId, record.id)'))
  assert(ui.includes('Buyer identity, payment and current availability are not verified.'))
  assert(service.includes("supabase.functions.invoke('verify-manual-freelancer-source'"))
})
