const test = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { join } = require('node:path')
const read = path => readFileSync(join(__dirname, '..', path), 'utf8')

test('Fiverr links get a manual label without claiming a connected API or changing DB classification', async () => {
  const { capturePlatform, manualCaptureSourceLabel, validateCaptureDraft } = await import('../src/lib/manualCaptureValidation.js')
  const real = 'https://www.fiverr.com/users/example'
  assert.equal(capturePlatform(real), 'other')
  assert.equal(manualCaptureSourceLabel(real, 'other'), 'Fiverr (manual)')
  assert.equal(manualCaptureSourceLabel('https://fiverr.com/example', 'other'), 'Fiverr (manual)')
  assert.equal(manualCaptureSourceLabel('https://seller.fiverr.com/example', 'other'), 'Fiverr (manual)')
  assert.equal(manualCaptureSourceLabel('https://fakefiverr.com/example', 'other'), 'Other (manual)')
  assert.equal(manualCaptureSourceLabel('https://fiverr.com.bad.example/project', 'other'), 'Other (manual)')
  assert.equal(manualCaptureSourceLabel('https://www.freelancer.com/projects/123', 'freelancer'), 'Freelancer')
  assert.equal(manualCaptureSourceLabel('https://www.upwork.com/jobs/example', 'upwork'), 'Upwork')
  const draft = validateCaptureDraft({url: real, title: 'Website work', requirement: 'A website project described by its buyer in public.'})
  assert.equal(draft.source_platform, 'other')
})

test('Sources Hub clearly distinguishes manual Fiverr from automatic provider metrics', () => {
  const hub = read('src/components/SourcesHubPage.jsx')
  assert(hub.includes('Manual only'))
  assert(hub.includes('No Fiverr API connection, automated scraping'))
  assert(hub.includes('Add Fiverr link with Quick Capture'))
  assert(hub.includes('onClick={() => setManualCaptureRequest(value => value + 1)}'))
  assert(hub.includes('openRequest={manualCaptureRequest}'))
  assert(hub.includes("['google', 'freelancer', 'upwork'].includes(row.source)"))
  assert(!hub.includes("SOURCE_ICONS = { google: Search, freelancer: BriefcaseBusiness, upwork: Plug, fiverr"))
})

test('Fiverr shortcut opens and focuses the existing review form without a provider call', () => {
  const panel = read('src/components/QuickCapturePanel.jsx')
  assert(panel.includes('openRequest = 0'))
  assert(panel.includes('if (openRequest > 0) setOpen(true)'))
  assert(panel.includes('linkInputRef.current?.focus({ preventScroll: true })'))
  assert(panel.includes('ref={linkInputRef}'))
  assert(panel.includes('manualCaptureSourceLabel(preview.source_url, preview.source_platform)'))
  assert(panel.includes('manualCaptureSourceLabel(record.source_url, record.source_platform)'))
  assert(panel.includes('saveManualCapture('))
  assert(panel.includes('Review capture'))
})

test('No Fiverr connector, automatic source selection or unsupported verification is introduced', () => {
  const app = read('src/App.jsx')
  const validation = read('src/lib/manualCaptureValidation.js')
  const sourceHub = read('src/components/SourcesHubPage.jsx')
  assert(!app.includes("key: 'fiverr'"))
  assert(!validation.includes("return 'fiverr'"))
  assert(!sourceHub.includes('Fiverr connected'))
  assert(!sourceHub.includes('Fiverr recently verified'))
  assert(!sourceHub.includes('fiverr.com/api'))
  assert(!sourceHub.includes('fetch('))
})
