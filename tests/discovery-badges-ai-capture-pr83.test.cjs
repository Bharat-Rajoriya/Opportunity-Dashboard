const test = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { join } = require('node:path')
const read = p => readFileSync(join(__dirname,'..',p),'utf8')

test('Discovery hover and active-disabled states preserve contrast in both themes', () => {
  const css = read('src/ui-quickcapture-review-pr83.css')
  const nav = read('src/components/DiscoveryJourneyNav.jsx')
  assert.match(css, /\.discovery-journey-step:not\(\.is-current\):hover:not\(:disabled\)/)
  assert.match(css, /html\[data-theme="dark"\].*\.discovery-journey-step:not\(\.is-current\):hover:not\(:disabled\)/)
  assert.match(css, /\.discovery-journey-step\.is-current:disabled/)
  assert.match(css, /color: #f3edff/)
  assert.match(css, /background: #303054/)
  assert.match(nav, /disabled=\{active === id\}/)
  assert.match(nav, /aria-current=\{active === id \? 'step' : undefined\}/)
})

test('review and ready count badges are legible in both themes without changing counts', () => {
  const css = read('src/ui-quickcapture-review-pr83.css')
  const app = read('src/App.jsx')
  assert.match(css, /html\[data-theme="dark"\] \.workspace-shell \.outreach-v2-count/)
  assert.match(css, /background: #31264a/)
  assert.match(css, /color: #e6d2ff/)
  assert.match(app, /className="outreach-v2-count"/)
  assert.match(app, /\.pending\} awaiting review/)
  assert.match(app, /\.ready\} ready/)
})

test('Quick Capture AI can only draft from user-entered title and description', () => {
  const panel = read('src/components/QuickCapturePanel.jsx')
  assert.match(panel, /fieldType: 'manual_capture_description'/)
  assert.match(panel, /roughText: requirement\.trim\(\)/)
  assert.match(panel, /context: \{ project_title: title\.trim\(\) \}/)
  assert.match(panel, /requirement\.trim\(\)\.length < 20/)
  assert.match(panel, /title\.trim\(\)\.length < 4/)
  assert.match(panel, /aiLoading \|\| saving/)
  assert.match(panel, /setAiDraft\(candidate\)/)
  assert.match(panel, /setRequirement\(aiDraft\)/)
  assert.match(panel, /Use this draft/)
  assert.match(panel, /Discard draft/)
  assert.match(panel, /does not open the link or verify its contents/i)
  assert.doesNotMatch(panel, /fetch\(url\)/)
})

test('manual copy backend requires JWT, workspace access and actual user notes', () => {
  const fn = read('supabase/functions/generate-onboarding-copy/index.ts')
  assert.match(fn, /withSupabase\(\s*\{ auth: 'user' \}/)
  assert.match(fn, /'manual_capture_description'/)
  assert.match(fn, /roughText.length < 20/)
  assert.match(fn, /roughText.length > 5000/)
  assert.match(fn, /context.project_title/)
  assert.match(fn, /\.from\('workspaces'\)/)
  assert.match(fn, /generatedText.length < 20 \|\| generatedText.length > 5000/)
  assert.doesNotMatch(fn, /source_url:/)
})

test('new scoped CSS is loaded last, and does not change project data', () => {
  const app=read('src/App.jsx')
  const css=read('src/ui-quickcapture-review-pr83.css')
  const imports=[...app.matchAll(/^import ['"]([^'"]+\.css)['"]$/gm)].map(m=>m[1])
  assert.equal(imports.at(-3),'./ui-quickcapture-review-pr83.css')
  assert(!css.includes('fetch('))
  assert(!css.includes('supabase.'))
  assert(css.includes('.quick-capture-ai-draft'))
})
