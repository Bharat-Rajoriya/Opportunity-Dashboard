const test = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { join } = require('node:path')
const read = p => readFileSync(join(__dirname, '..', p), 'utf8')

test('source observation is scoped to signed-in owner and previously qualified capture', () => {
  const sql = read('supabase/migrations/20261108221500_manual_source_evidence_review_v1.sql')
  assert(sql.includes('auth.uid()'))
  assert(sql.includes('w.owner_user_id=auth.uid()'))
  assert(sql.includes("v_capture.status <> 'qualified'"))
  assert(sql.includes('o.workspace_id=p_workspace_id'))
  assert(sql.includes('o.source_item_id=v_capture.id::text'))
  assert(sql.includes('grant execute on function public.record_manual_capture_source_review'))
  assert(!sql.includes("source_verified',true"))
  assert(!sql.includes('total_score='))
  assert(!sql.includes('outreach_status='))
})
test('review UI records observation without claiming independent verification', () => {
  const ui = read('src/components/QuickCapturePanel.jsx')
  const service = read('src/services/manualCaptures.js')
  assert(ui.includes('Appeared open'))
  assert(ui.includes('Unavailable'))
  assert(ui.includes('Unclear'))
  assert(ui.includes('buyer and authenticity still unverified'))
  assert(service.includes("supabase.rpc('record_manual_capture_source_review'"))
  assert(!service.includes('source_verified: true'))
})
