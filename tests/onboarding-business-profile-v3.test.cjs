const test = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { join } = require('node:path')
const { pathToFileURL } = require('node:url')

const read = path => readFileSync(join(__dirname, '..', path), 'utf8')
const load = import(pathToFileURL(join(__dirname, '../src/config/profileExperience.js')).href)

test('V3 groups exactly five existing onboarding steps into three non-interactive milestones', async () => {
  const { ONBOARDING_STEPS, ONBOARDING_MILESTONES, getOnboardingMilestone } = await load
  assert.equal(ONBOARDING_STEPS.length, 5)
  assert.equal(ONBOARDING_MILESTONES.length, 3)
  assert.deepEqual(ONBOARDING_MILESTONES.flatMap(item => item.stepIds), [1, 2, 3, 4, 5])
  assert.equal(getOnboardingMilestone(1).id, 'identity')
  assert.equal(getOnboardingMilestone(2).id, 'identity')
  assert.equal(getOnboardingMilestone(3).id, 'buyers')
  assert.equal(getOnboardingMilestone(4).id, 'buyers')
  assert.equal(getOnboardingMilestone(5).id, 'trust')
  assert.equal(getOnboardingMilestone(0).id, 'identity')
})

