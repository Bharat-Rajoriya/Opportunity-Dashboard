const test = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { join } = require('node:path')
const read = path => readFileSync(join(__dirname,'..',path),'utf8')

test('Search V2 keeps three primary selectors and progressively discloses advanced filters', () => {
  const page = read('src/components/UnifiedSearchPage.jsx')
  const primary = page.slice(page.indexOf('className="unified-search-filters"'), page.indexOf('className="unified-search-advanced-toggle-row"'))
  const advanced = page.slice(page.indexOf('className="unified-search-filters unified-search-advanced-panel"'),page.indexOf('className="unified-search-active-chips"'))
  for (const label of ['Source','Posted','Score']) assert(primary.includes('>'+label+'\n'))
  for (const label of ['Country','Budget evidence','Project type','Work arrangement']) assert(advanced.includes('>'+label+'\n'))
  assert(!primary.includes('>Budget evidence'))
  assert(page.includes('aria-expanded={advancedOpen}'))
  assert(page.includes('aria-controls="unified-search-advanced-filters"'))
  assert(page.includes("initialPreset[key] || 'all'"))
})

test('Empty results offer a smaller adjustment before resetting all filters', () => {
  const page = read('src/components/UnifiedSearchPage.jsx')
  assert(page.includes('const clearMostRestrictive = () => {'))
  assert(page.includes('Remove a restrictive filter'))
  assert(page.includes('Clear all filters'))
  assert(page.includes('These listings do not confirm remote work'))
  assert(!page.includes('Unknown budget: {uncertainCounts.budget}'))
  assert(page.includes('activeFilters.map(item =>'))
  assert(page.includes('onClick={item.clear}'))
})

test('Search keeps saved presets, discovery separation and original matching semantics', () => {
  const page = read('src/components/UnifiedSearchPage.jsx')
  assert(page.includes('matchesAdvancedFilters(item'))
  assert(page.includes('budget_evidence: budgetEvidence, project_kind: projectKind, work_mode: workMode'))
  assert(page.includes('saveOpen && <div className="unified-search-save"'))
  assert(page.includes('onClick={onOpenDiscovery}'))
  assert(!page.includes('triggerOpportunityEngine('))
  const css = read('src/components/UnifiedSearchPage.css')
  assert(css.includes('.unified-search-advanced-panel'))
  assert(css.includes('.unified-search-active-chips'))
})
